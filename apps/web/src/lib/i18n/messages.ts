export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "zh";
}

export function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translateMessage(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const table = MESSAGES[locale];
  if (table[key]) return formatMessage(table[key], vars);
  const patterns: [RegExp, string, string][] = [
    [/^Transaction would fail: (.+)$/, "Transaction would fail: {reason}", "reason"],
    [/^Request failed \((\d+)\)$/, "Request failed ({status})", "status"],
    [/^Could not open file \((\d+)\)$/, "Could not open file ({status})", "status"],
    [/^Too small: expected string to have >=(\d+) characters$/, "Too small: expected string to have >={count} characters", "count"],
    [/^Too big: expected string to have <=(\d+) characters$/, "Too big: expected string to have <={count} characters", "count"],
  ];
  for (const [pattern, template, parameter] of patterns) {
    const match = key.match(pattern);
    if (match) return formatMessage(table[template], { [parameter]: match[1] });
  }
  if (/^(name|description|imageUrl|website|registrationNo|title|summary|category|location|usage|text): /.test(key)) {
    return key.split("; ").map((issue) => {
      const separator = issue.indexOf(": ");
      return `${translateMessage(locale, issue.slice(0, separator))}: ${translateMessage(locale, issue.slice(separator + 2))}`;
    }).join("; ");
  }
  return formatMessage(MESSAGES.en[key] ?? key, vars);
}

