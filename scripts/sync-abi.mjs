// Generates typed ABIs and deployment addresses for the web app from Foundry output.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "contracts", "out");
const deploymentsDir = join(root, "contracts", "deployments");
const targetDir = join(root, "apps", "web", "src", "contracts");

const contracts = [
  "MockUSDC",
  "MerchantRegistry",
  "CharityRegistry",
  "PauseController",
  "ProductCampaign",
  "CheckoutRouter",
  "EvidenceRegistry",
  "ImpactReportRegistry",
  "TreasuryFactory",
  "DonationTreasury",
];

mkdirSync(targetDir, { recursive: true });

let abis = "// Generated by scripts/sync-abi.mjs. Do not edit.\n\n";
for (const name of contracts) {
  const file = join(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    console.error(`Missing ${file}. Run "forge build" in contracts/ first.`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  const exportName = name[0].toLowerCase() + name.slice(1) + "Abi";
  abis += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(targetDir, "abis.ts"), abis);

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((n) => n.endsWith(".json"))) {
    const data = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    deployments[data.chainId] = data;
  }
}
writeFileSync(
  join(targetDir, "deployments.ts"),
  `// Generated by scripts/sync-abi.mjs. Do not edit.\n\nexport type Deployment = {\n  chainId: number;\n  deployBlock: number;\n  admin: \`0x\${string}\`;\n  platformReceiver: \`0x\${string}\`;\n  MockUSDC: \`0x\${string}\`;\n  MerchantRegistry: \`0x\${string}\`;\n  CharityRegistry: \`0x\${string}\`;\n  PauseController: \`0x\${string}\`;\n  ProductCampaign: \`0x\${string}\`;\n  EvidenceRegistry: \`0x\${string}\`;\n  ImpactReportRegistry: \`0x\${string}\`;\n  TreasuryFactory: \`0x\${string}\`;\n  CheckoutRouter: \`0x\${string}\`;\n};\n\nexport const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);

console.log(`Wrote ABIs for ${contracts.length} contracts and ${Object.keys(deployments).length} deployment(s).`);
